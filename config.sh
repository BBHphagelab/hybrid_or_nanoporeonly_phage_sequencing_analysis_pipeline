# high depth refines bases in UNIQUE regions but cannot resolve structure across
# repeats/DTRs, so structure stays ONT-defined. (The former Unicycler hybrid +
# forced-single-contig SPAdes fallback have been REMOVED — they risked chimeric
# junctions at DTR boundaries.)
#
# A single contig is now a REPORTED QC metric, not an assembly target: the
# assembler output stands as-is. If a genome stays fragmented, step 02 exposes
# the assembly graph (for_bandage.gfa) for optional manual finishing in Bandage.
# See MANUAL_FINISHING.md for the exact procedure.

# ── Single-contig finishing (step 02) ────────────────────────────────────────
# finish_assembly.py detects terminal repeats (DTR) / circular overhangs and, if
# the assembly stays fragmented, exposes the assembly graph (for_bandage.gfa) for
# manual finishing in Bandage (see MANUAL_FINISHING.md). Trimming circular
# overhangs is OFF by default to protect real short phage DTRs (e.g. T7 ~160 bp);
