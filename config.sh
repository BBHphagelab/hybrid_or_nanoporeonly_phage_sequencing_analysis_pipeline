activate_env() {
    if [[ "${MAMBA_DEFAULT_ENV:-}" == "${MAMBA_ENV}" ]]; then return; fi

    local mamba_bin="${MAMBA_ROOT_PREFIX}/bin/micromamba"

    if [[ ! -x "${mamba_bin}" ]]; then
        die "micromamba not found at ${mamba_bin}.
    Run 00_install_env.sh first, or set MAMBA_ROOT_PREFIX in config.sh.
    Default install location: \${HOME}/.mamba"
    fi

    export MAMBA_ROOT_PREFIX
    eval "$("${mamba_bin}" shell hook --shell bash)"
    micromamba activate "${MAMBA_ENV}" \
        || die "Cannot activate micromamba env '${MAMBA_ENV}'.
    Create it with: bash 00_install_env.sh"
}

# Load samtools from the Maestro cluster module system.
# The samtools bundled inside the micromamba env is prehistoric (< 0.1.19)
# and does not support `--version`, `sort -O`, `coverage`, etc.
# Maestro ships samtools/1.21 via Lmod.
#
# CONCURRENCY-SAFE: we NEVER mutate the shared micromamba env binary (the old
# version rewrote ${env}/bin/samtools with a wrapper, so parallel array tasks
# raced on the same file and could corrupt it mid-run). Instead we expose the
# module's samtools through a PER-PROCESS wrapper directory created with
# `mktemp -d` and PREPENDED to PATH — private to this task, cleaned up on exit.
# Falls back silently to the env samtools if the module system is absent (local dev).
load_samtools_cluster() {
    command -v module &>/dev/null || {
        echo "[WARN] module system not available — using env samtools (may be outdated)" >&2
        return 0
    }

    module load samtools/1.21 2>/dev/null \
        || module load samtools 2>/dev/null \
        || { echo "[WARN] module load samtools failed — using env samtools (may be outdated)" >&2; return 0; }

    local module_st
    module_st=$(command -v samtools 2>/dev/null)
    local env_st="${MAMBA_ROOT_PREFIX}/envs/${MAMBA_ENV}/bin/samtools"

    if [[ -n "${module_st}" && "${module_st}" != "${env_st}" ]]; then
        local wrap_dir
        wrap_dir=$(mktemp -d "${TMPDIR:-/tmp}/samtools_wrap_XXXXXX")
        ln -sf "${module_st}" "${wrap_dir}/samtools" 2>/dev/null \
            || { printf '#!/bin/bash\nexec "%s" "$@"\n' "${module_st}" > "${wrap_dir}/samtools"; chmod +x "${wrap_dir}/samtools"; }
        export PATH="${wrap_dir}:${PATH}"
        trap 'rm -rf "'"${wrap_dir}"'"' EXIT
    fi

    local st_ver
    st_ver=$(samtools --version 2>&1 | head -1 || echo "unknown")
    echo "[INFO] samtools active: ${st_ver}  (path: $(command -v samtools 2>/dev/null))"
}

# Force modkit 0.2.x to the FRONT of PATH for MicrobeMod (which needs the
# `--only-tabs` flag removed in modkit ≥ 0.3). Same concurrency-safe pattern as
# load_samtools_cluster: a PER-PROCESS wrapper dir (never mutates a shared env).
# Returns non-zero (and warns loudly) if MODKIT_02X_BIN is missing — the caller
# stays non-fatal so the failure is still recorded by the sentinel logic.
use_modkit_02x() {
    local bin="${MODKIT_02X_BIN:-}"
    if [[ -z "${bin}" || ! -x "${bin}" ]]; then
        warn "modkit 0.2.x not found at MODKIT_02X_BIN='${bin}'."
        warn "  MicrobeMod 1.1.0 needs modkit 0.2.x (--only-tabs). Install once:"
        warn "  micromamba create -n modkit_0.2 -c bioconda -c conda-forge ont-modkit=0.2.6"
        return 1
    fi
    local ver
    ver=$("${bin}" --version 2>&1 | head -1 || echo "unknown")
    case "${ver}" in
        *0.2.*) : ;;
        *) warn "MODKIT_02X_BIN reports '${ver}' (expected 0.2.x) — MicrobeMod may still fail on --only-tabs." ;;
    esac
    local d
    d=$(mktemp -d "${TMPDIR:-/tmp}/modkit02_XXXXXX")
    ln -sf "${bin}" "${d}/modkit" 2>/dev/null \
        || { printf '#!/bin/bash\nexec "%s" "$@"\n' "${bin}" > "${d}/modkit"; chmod +x "${d}/modkit"; }
    export PATH="${d}:${PATH}"
    echo "[INFO] modkit active: ${ver}  (path: $(command -v modkit 2>/dev/null))"
}

# Read a field from the sample sheet by barcode
get_sample_field() {
    local barcode="$1" field="$2"
    local header idx value
    header=$(grep -v '^#' "${RESULTS_DIR}/sample_sheet.tsv" | head -1)
    idx=$(echo "$header" | tr '\t' '\n' | grep -n "^${field}$" | cut -d: -f1)
    [[ -z "$idx" ]] && die "Field '${field}' not found in sample_sheet.tsv"
    value=$(grep "^${barcode}"$'\t' "${RESULTS_DIR}/sample_sheet.tsv" \
              | cut -f"${idx}")
    echo "$value"
}

# List all barcodes in the sample sheet (skipping header and comment lines)
list_barcodes() {
    grep -v '^#' "${RESULTS_DIR}/sample_sheet.tsv" \
        | tail -n +2 \
        | cut -f1
}

# Count barcodes in the sample sheet
count_barcodes() {
    list_barcodes | wc -l | tr -d ' '
}
